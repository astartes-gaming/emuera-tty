/// The Japanese name for a config key written either way.
pub fn canonical(key: &str) -> &str {
    let k = key.trim();
    for (jp, en) in NAMES {
        if k == *jp || k.eq_ignore_ascii_case(en) {
            return jp;
        }
    }
    k
}
